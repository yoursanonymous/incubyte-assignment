#!/usr/bin/env node
// Runs every test suite and writes reports/TEST_REPORT.md from the *actual* results.
// Usage: node scripts/test-report.mjs   (needs PostgreSQL; e2e needs Playwright's Chromium)
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const reports = join(root, 'reports');
mkdirSync(reports, { recursive: true });

const run = (command, cwd) => {
  const started = Date.now();
  try {
    execSync(command, {
      cwd: join(root, cwd),
      stdio: 'pipe',
      env: process.env,
      maxBuffer: 64 * 1024 * 1024,
    });
    return { ok: true, seconds: (Date.now() - started) / 1000 };
  } catch (error) {
    return {
      ok: false,
      seconds: (Date.now() - started) / 1000,
      output: (String(error.stderr ?? '') + String(error.stdout ?? '')).slice(0, 1500),
    };
  }
};
const readJson = (path) => (existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : null);
const sh = (cmd) => {
  try {
    return execSync(cmd, { encoding: 'utf8' }).trim();
  } catch {
    return 'n/a';
  }
};

function summarise(vitestJson, filter = () => true) {
  const files = (vitestJson?.testResults ?? []).filter((f) => filter(f.name));
  const tests = files.flatMap((f) => f.assertionResults);
  const count = (s) => tests.filter((t) => t.status === s).length;
  return {
    files: files.length,
    total: tests.length,
    passed: count('passed'),
    failed: count('failed'),
    skipped: count('skipped') + count('pending') + count('todo'),
  };
}
const coverage = (path) => {
  const total = readJson(path)?.total;
  return total
    ? `${total.lines.pct}% lines · ${total.statements.pct}% statements · ${total.branches.pct}% branches · ${total.functions.pct}% functions`
    : 'not measured';
};

const steps = {
  backend: run(
    'npx vitest run --coverage --reporter=json --outputFile=../reports/backend-results.json',
    'backend',
  ),
  frontend: run(
    'npx vitest run --coverage --reporter=json --outputFile=../reports/frontend-results.json',
    'frontend',
  ),
  build: run('npm run build', '.'),
  e2e: run('npx playwright test', 'e2e'),
};

const backend = readJson(join(reports, 'backend-results.json'));
const frontend = readJson(join(reports, 'frontend-results.json'));
const e2e = readJson(join(reports, 'e2e-results.json'));
const unit = summarise(backend, (n) => n.includes('/tests/unit/'));
const integration = summarise(backend, (n) => n.includes('/tests/integration/'));
const ui = summarise(frontend);
const e2eStats = e2e?.stats ?? { expected: 0, unexpected: 0, skipped: 0, flaky: 0 };

const row = (name, s, secs) =>
  `| ${name} | ${s.files} | ${s.total} | ${s.passed} | ${s.failed} | ${s.skipped} | ${secs?.toFixed?.(1) ?? '-'} s |`;
const status = (r) => (r.ok ? 'PASS' : 'FAIL');

const md = `# Test report

Generated by \`node scripts/test-report.mjs\` from real executions on ${new Date().toISOString()}.

${process.env.PRISMA_SCHEMA_ENGINE_BINARY ? '> **Sandbox note:** the Prisma schema-engine download was blocked by the network policy, so `PRISMA_SCHEMA_ENGINE_BINARY` was stubbed. `prisma generate` and runtime queries do not need that engine; `prisma migrate` was NOT exercised here (migrations were applied as plain SQL by the test setup).\n\n' : ''}**Environment:** Node ${process.version} · ${sh('psql --version')} · ${sh('uname -sr')} · ${sh('nproc')} CPU(s)

| Suite | Files | Tests | Passed | Failed | Skipped | Duration |
|---|---:|---:|---:|---:|---:|---:|
${row('Backend unit', unit)}
${row('Backend integration (real PostgreSQL)', integration)}
${row('Frontend (Testing Library + jsdom)', ui, steps.frontend.seconds)}
| End-to-end (Playwright, real browser + API + DB) | ${e2e ? (e2e.suites?.length ?? '-') : 0} | ${e2eStats.expected + e2eStats.unexpected + e2eStats.skipped + e2eStats.flaky} | ${e2eStats.expected} | ${e2eStats.unexpected} | ${e2eStats.skipped} | ${steps.e2e.seconds.toFixed(1)} s |

Backend unit + integration ran together in ${steps.backend.seconds.toFixed(1)} s.

## Quality gates

| Gate | Result |
|---|---|
| Backend tests | ${status(steps.backend)} |
| Frontend tests | ${status(steps.frontend)} |
| Production builds (backend + frontend) | ${status(steps.build)} |
| End-to-end | ${status(steps.e2e)} |

## Coverage (v8)

* Backend: ${coverage(join(root, 'backend/coverage/coverage-summary.json'))}
* Frontend: ${coverage(join(root, 'frontend/coverage/coverage-summary.json'))}

Coverage is a supporting signal. The invariants (no oversell, atomic rollback, idempotent replay, role enforcement) are verified by explicit tests and by mutation checks recorded in docs/testing.md.

${Object.entries(steps)
  .filter(([, r]) => !r.ok)
  .map(([k, r]) => `## Failure output: ${k}\n\n\`\`\`\n${r.output}\n\`\`\``)
  .join('\n\n')}
`;
writeFileSync(join(reports, 'TEST_REPORT.md'), md);
console.log(md);
process.exit(Object.values(steps).every((s) => s.ok) ? 0 : 1);
